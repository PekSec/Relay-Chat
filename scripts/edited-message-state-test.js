import assert from 'node:assert/strict';
import useConversation from '../frontend/src/zustand/useConversation.js';
const state = () => useConversation.getState();
const original = { _id: '02', message: 'Original' };
const conversation = { _id: 'peer', lastMessage: original };
const latest = { messageId: '02', newMessage: 'New\ntext', isEdited: true, editedAt: '2026-09-27T12:00:02.000Z' };
state().reset();
state().setMessageEdited(latest);
state().setMessageEdited({ ...latest, newMessage: 'Older', editedAt: '2026-09-27T12:00:01.000Z' });
state().setSelectedConversation(conversation);
state().setMessages([original]);
state().setConversations([conversation]);
assert.equal(state().messages[0].message, latest.newMessage);
assert.equal(state().selectedConversation.lastMessage.message, latest.newMessage);
assert.equal(state().conversations[0].lastMessage.message, latest.newMessage);
state().markMessageDeleted('02');
state().setMessageEdited({ ...latest, editedAt: '2026-09-27T12:00:03.000Z' });
assert.equal(state().messages[0].isDeleted, true);
assert.equal(state().conversations[0].lastMessage.message, 'Bu mesaj silindi');
state().clearHistory('peer', '02');
state().setMessages([original]);
state().setConversations([conversation]);
assert.equal(state().messages.length, 0);
assert.equal(state().conversations[0].lastMessage, null);
state().reset();
state().setMessages([original]);
assert.equal(state().messages[0].message, 'Original');
const newer = { _id: '03', message: 'New arrival' };
state().setConversations([{ ...conversation, lastMessage: newer }]);
state().setSelectedConversation({ ...conversation, lastMessage: newer });
state().setConversations([conversation]);
state().setSelectedConversation(conversation);
assert.equal(state().conversations[0].lastMessage._id, '03', 'late send/history cannot roll back preview');
assert.equal(state().selectedConversation.lastMessage._id, '03');
state().reset();
console.log('PASS edit before history, ordered updates, previews, deletion, clear, account reset');
