import assert from 'node:assert/strict';
import useConversation from '../frontend/src/zustand/useConversation.js';
import useFriendStore from '../frontend/src/zustand/useFriend.js';

const state = () => useConversation.getState();
const old = { _id: '000000000000000000000001', message: 'Old' };
const newer = { _id: '000000000000000000000002', message: 'New' };
const peer = { _id: 'peer', lastMessage: old };
state().reset(); state().setSelectedConversation(peer);
state().setMessages([old, newer]); state().setConversations([{ ...peer, lastMessage: newer }]);
state().clearHistory(peer._id, old._id);
assert.deepEqual(state().messages, [newer]);
assert.equal(state().conversations[0].lastMessage._id, newer._id);
state().setMessages([old, newer]);
assert.deepEqual(state().messages, [newer], 'late history cannot restore cleared records');
state().setConversations([peer]);
assert.equal(state().conversations[0].lastMessage._id, newer._id, 'stale preview must retain a known newer message');
state().setConversations([{ ...peer, lastMessage: null }]);
assert.equal(state().conversations[0].lastMessage._id, newer._id, 'empty snapshot predating a new message must retain it');
useFriendStore.getState().setMessageRequests([{ ...peer, lastMessage: newer }]);
useFriendStore.getState().setMessageRequests([peer]);
assert.equal(useFriendStore.getState().messageRequests[0]?.lastMessage._id, newer._id, 'stale request snapshot must retain a new incoming request');
state().setSelectedConversation(peer);
assert.equal(state().selectedConversation.lastMessage, null);
state().clearHistory(peer._id, newer._id);
state().setConversations([peer]);
assert.equal(state().conversations[0].lastMessage, null);
state().clearHistory(peer._id, old._id);
state().setMessages([old, newer]);
assert.equal(state().messages.length, 0, 'late clear cannot move boundary backwards');
state().setSelectedConversation({ _id: 'other' }); state().setMessages([old]);
state().clearHistory(peer._id, newer._id);
assert.equal(state().messages.length, 1, 'clearing one peer leaves another open history intact');
state().reset(); state().setSelectedConversation(peer); state().setMessages([old]);
assert.equal(state().messages.length, 1, 'clear boundaries cannot cross sessions');
state().reset();
useFriendStore.getState().reset();
console.log('PASS late history/list, new messages, monotonic clear, other conversation, session reset');
